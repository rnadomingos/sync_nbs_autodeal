from include.infra.postgres_database import PostgresSessionLocal
from sqlalchemy.dialects.postgresql import insert
from sqlalchemy.orm import declarative_base
from sqlalchemy.exc import SQLAlchemyError
from sqlalchemy import case, func
from typing import Type, TypeVar, Any, cast
from tqdm import tqdm
import pandas as pd

Base = declarative_base()

#TypeVar to data_model
BaseModel = TypeVar("T", bound=Base)  # type: ignore

# Colunas de controle interno que jamais devem ser sobrescritas no ON CONFLICT DO UPDATE.
# - id: PK autoincrement, imutável.
# - created_at: data de criação, deve ser definida apenas no INSERT.
# - updated_at: atualizado condicionalmente (somente quando há mudança real nos dados).
# - sent_autodeal / sent_at_autodeal / updated_at_autodeal: controlam o ciclo de envio
#   à API Autonox; sobrescrevê-los causaria reenvio desnecessário de OS já enviadas.
_READONLY_COLUMNS = frozenset({
    "id",
    "created_at",
    "updated_at",
    "sent_autodeal",
    "sent_at_autodeal",
    "updated_at_autodeal",
})


class UpsertData:
    def __init__(
            self,
            data_frame: pd.DataFrame,
            data_model: Type[BaseModel],
            conflict_keys: list[str]
            ) -> None:
        self.data_frame = data_frame
        self.data_model = data_model
        self.conflict_keys = conflict_keys

    def save_data(self) -> list[dict]:
        """
        Performs an UPSERT (insert or update on conflict) operation into a PostgreSQL database using a generic SQLAlchemy ORM model.

        This function takes a validated Pandera DataFrameModel and attempts to insert each row into the specified table
        represented by the SQLAlchemy model. If a record with the specified conflict keys already exists, it will be updated
        with the new values provided in the DataFrame.

        Columns in _READONLY_COLUMNS are excluded from the ON CONFLICT SET clause to avoid:
        - Resetting audit/control timestamps (created_at, updated_at).
        - Triggering unnecessary re-sends to the Autonox API by bumping updated_at on
          rows whose business data has not actually changed.

        The `updated_at` column is updated conditionally: only when at least one business
        data column differs from the existing row value, using IS DISTINCT FROM for
        NULL-safe comparison, wrapped in a CASE expression generated by SQLAlchemy.

        Args:
            data_frame (pa.DataFrameModel): A validated Pandera DataFrameModel containing the data to be inserted or updated.
            data_model (Type[BaseModel]): A SQLAlchemy ORM model class representing the target database table.
            conflict_keys (list[str]): List of column names that define the uniqueness constraint to detect conflicts during insertion.

        Returns:
            list[dict]: A list of dictionaries representing the rows that were inserted or updated in the database.

        Raises:
            SQLAlchemyError: If any error occurs during the database operation, the transaction is rolled back and the error is re-raised.
        """
        with PostgresSessionLocal() as db:
            try:
                rows = cast(
                    list[dict[str, Any]],
                    self.data_frame.where(pd.notnull(self.data_frame), None).to_dict(orient="records")
                )

                for row in tqdm(rows, desc=f"Upserting {self.data_model.__tablename__}", unit="row"):
                    stmt = insert(self.data_model).values(**row)

                    # Colunas de negócio: excluem conflict_keys e colunas de controle interno.
                    # Somente essas são atualizadas no ON CONFLICT DO UPDATE.
                    excluded_from_update = set(self.conflict_keys) | _READONLY_COLUMNS
                    business_columns = [
                        c for c in self.data_model.__table__.columns
                        if c.name not in excluded_from_update
                    ]

                    update_dict = {
                        c.name: stmt.excluded[c.name]
                        for c in business_columns
                    }

                    # Atualiza updated_at apenas quando algum campo de negócio mudou.
                    # IS DISTINCT FROM trata NULLs corretamente (NULL IS DISTINCT FROM NULL = false).
                    table_columns = {c.name for c in self.data_model.__table__.columns}
                    if business_columns and "updated_at" in table_columns:
                        change_detected = None
                        for c in business_columns:
                            table_col = self.data_model.__table__.c[c.name]
                            condition = table_col.is_distinct_from(stmt.excluded[c.name])
                            change_detected = (
                                condition if change_detected is None
                                else (change_detected | condition)
                            )

                        update_dict["updated_at"] = case(
                            (change_detected, func.now()),
                            else_=self.data_model.__table__.c["updated_at"]
                        )

                    if update_dict:
                        stmt = stmt.on_conflict_do_update(
                            index_elements=self.conflict_keys,
                            set_=update_dict
                        )
                    else:
                        stmt = stmt.on_conflict_do_nothing(
                            index_elements=self.conflict_keys
                        )

                    db.execute(stmt)
                db.commit()
                return rows
            except SQLAlchemyError as e:
                db.rollback()
                print("Error saving to the database:")
                print(e.__class__.__name__, "-", str(e))
                raise